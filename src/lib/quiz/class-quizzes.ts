function shuffled(question: QuizQuestionData, random: () => number): QuizQuestionData {
  const correct = question.options[question.correctIndex];
  const options = [...question.options];
  for (let index = options.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [options[index], options[swap]] = [options[swap], options[index]];
  }
  return { ...question, options, correctIndex: options.indexOf(correct) };
}

/** All class quizzes, each with its answers in a new random order. */
export function listClassQuizzes(random: () => number = Math.random): ClassQuiz[] {
  return CLASS_QUIZZES.map((quiz) => ({ ...quiz, questions: quiz.questions.map((question) => shuffled(question, random)) }));
}

export function getClassQuiz(id: string, random: () => number = Math.random): ClassQuiz | undefined {
  return listClassQuizzes(random).find((quiz) => quiz.id === id);
}
