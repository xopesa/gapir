/** The correct answer is written first; the order is shuffled when the quiz is used. */
function q(text: string, correct: string, ...wrong: string[]): QuizQuestionData {
  return { text, options: [correct, ...wrong], correctIndex: 0, timeLimitSec: 20 };
}

