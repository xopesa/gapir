// Converts prisma/migrations/<name>/migration.sql into the flat, numbered
// layout that `wrangler d1 migrations apply` expects (migrations/0001_<name>.sql).
// Prisma stays the source of truth: create migrations with Prisma, then rerun this.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const source = resolve("prisma/migrations");
const target = resolve("migrations");
mkdirSync(target, { recursive: true });

// D1 always enforces foreign keys and rejects some PRAGMAs, so they are dropped.
const UNSUPPORTED = /^[ \t]*PRAGMA[ \t]+(foreign_keys|optimize)\b.*$/gim;

const names = readdirSync(source, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

names.forEach((name, index) => {
  const sql = readFileSync(resolve(source, name, "migration.sql"), "utf8")
    .replace(/\r\n/g, "\n")
    .replace(UNSUPPORTED, "-- $& (removed for D1)");
  const file = resolve(target, `${String(index + 1).padStart(4, "0")}_${name}.sql`);
  const content = `-- Generated by scripts/d1-migrations.mjs from prisma/migrations/${name}. Do not edit by hand.\n${sql}`;
  const changed = !existsSync(file) || readFileSync(file, "utf8") !== content;
  if (changed) writeFileSync(file, content);
  console.log(`${changed ? "wrote" : "ok   "} ${file}`);
});
