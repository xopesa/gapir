// Embeds ai/prompts/<direction>/tutor/v1.md into a TS module so prompts work
// on Cloudflare Workers, where the project files are not on disk.
// Usage: node scripts/build-prompts.mjs [--check]
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve("ai/prompts");
const output = resolve("src/server/ai/prompts/templates.generated.ts");

const directions = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => existsSync(resolve(root, name, "tutor", "v1.md")))
  .sort();

const entries = directions
  .map((direction) => {
    const text = readFileSync(resolve(root, direction, "tutor", "v1.md"), "utf8").replace(/\r\n/g, "\n");
    return `  ${JSON.stringify(direction)}: ${JSON.stringify(text)},`;
  })
  .join("\n");

const content = `// Generated by scripts/build-prompts.mjs from ai/prompts/*/tutor/v1.md. Do not edit by hand.
export const tutorPromptTemplates: Record<string, string> = {
${entries}
};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current !== content) {
    console.error("templates.generated.ts is out of date. Run: npm run prompts:build");
    process.exit(1);
  }
  console.log("Prompt templates are up to date");
} else {
  writeFileSync(output, content);
  console.log(`Embedded ${directions.length} tutor prompt(s) into ${output}`);
}
