// Generates cloudflare-env.d.ts (bindings + Workers runtime types).
// Local .env values are not read (only wrangler.jsonc), and the NodeJS.ProcessEnv
// augmentation is removed: it would make every variable required in process.env.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";

const output = resolve("cloudflare-env.d.ts");
const emptyDir = mkdtempSync(join(tmpdir(), "gapir-typegen-"));
const emptyEnv = join(emptyDir, ".env");
writeFileSync(emptyEnv, "");

const result = spawnSync(
  "npx",
  // The output path goes first: --env-file is an array option and would swallow it.
  ["wrangler", "types", output, "--env-interface", "CloudflareEnv", `--env-file=${emptyEnv}`],
  { stdio: "inherit", shell: process.platform === "win32" },
);
rmSync(emptyDir, { recursive: true, force: true });
if (result.status !== 0) process.exit(result.status ?? 1);

const content = readFileSync(output, "utf8");
const stripped = content
  .replace(/declare namespace NodeJS \{[\s\S]*?\n\}\n/, "")
  // Keep machine-specific paths out of the committed header.
  .replace(/^(\/\/ Generated by Wrangler by running `).*?(` \(hash)/m, "$1npm run cf:typegen$2");
if (stripped === content) console.warn("NodeJS.ProcessEnv block not found; left file unchanged");
writeFileSync(output, stripped);
